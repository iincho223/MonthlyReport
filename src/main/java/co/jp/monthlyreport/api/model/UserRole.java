package co.jp.monthlyreport.api.model;

/**
 * ユーザーロール定義。
 * ロール上下関係: NG &lt; TM &lt; TL &lt; GL &lt; OM
 * SP / SM はエスカレーション管理の特例ロール（営業担当者 / 支店長）。
 * SA はすべてのロールを横断的に管理する特例ロール（システム管理者）。
 */
public enum UserRole {
  /** 新卒：月報の提出・閲覧不可。エスカレーション機能へのアクセス不可。 */
  NG,
  /** メンバー：自分の月報のみ。エスカレーション機能へのアクセス不可。 */
  TM,
  /** チームリーダー：自分 + 同一チームの月報・エスカレーションを管理。 */
  TL,
  /** グループリーダー：自分 + 同一グループの月報・エスカレーションを管理。 */
  GL,
  /** オフィスマネージャー：営業所内全件の月報・エスカレーションを管理。 */
  OM,
  /** 営業担当者（特例）：自身が担当のエスカレーションを管理。 */
  SP,
  /** 支店長（特例）：営業所に所属する全エスカレーションを管理。 */
  SM,
  /** システム管理者（特例）：全ロールを横断管理。月報・エスカレーションはマスク表示。 */
  SA;

  /**
   * 月報への回答（フィードバック）権限を持つか判定する。
   * TL / GL / OM のみ回答可能。
   *
   * @return 回答可能な場合 true
   */
  public boolean canRespond() {
    return this == TL || this == GL || this == OM;
  }

  /**
   * エスカレーション機能へのアクセス権限を持つか判定する。
   * NG / TM はアクセス不可。
   *
   * @return アクセス可能な場合 true
   */
  public boolean canAccessEscalation() {
    return this != NG && this != TM;
  }
}
